"""Verify retained Linux frames and render the same-work three-arm paper table.

This is a passive data consumer. It opens no sockets and executes no campaign.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from verify_durable_workflow_mws import verify, require

DATA = ROOT / 'results/durable-mws-linux'
FAMILIES = (('sparse_cut', 'Sparse cut'), ('dense_cut', 'Dense cut'),
            ('low_conflict', 'Low conflict'))
ARMS = ('scanning', 'indexed', 'mws_small_table')


def retained():
    binding = json.loads((DATA / 'source-before.json').read_text(encoding='utf-8'))
    for name, digest in binding.items():
        require(hashlib.sha256((DATA / 'source-preimage' / name).read_bytes()).hexdigest()
                == digest, 'measured source preimage differs')
    result = verify(DATA)
    require(result == json.loads((DATA / 'verified-summary.json').read_text(encoding='utf-8')),
            'saved Linux verification summary differs from retained raw evidence')
    return result


def table(result):
    costs = {(row['family'], row['implementation']): row
             for row in result['costs_128_handles']}
    expected = {(family, arm) for family, _ in FAMILIES for arm in ARMS}
    require(set(costs) == expected and len(result['costs_128_handles']) == 9,
            'table requires all three arms and graph families')
    require(all(row['handles'] == 128 and row['seeds'] == 2 for row in costs.values()),
            'table requires two complete 128-handle cases per arm')
    lines = [r'% Generated by artifact/scripts/render_durable_mws.py from retained Linux raw frames.',
             r'\begin{table}[t]\centering',
             r'\caption{Same-work Linux durable workflows (ms, 128 handles).}',
             r'\label{tab:mws-workflow}\footnotesize',
             r'\begin{tabular}{lrrr}\toprule',
             r'Family & Scanning & Indexed & Corrected MWS\\\midrule']
    for family, label in FAMILIES:
        values = [f"{costs[family, arm]['median_workflow_ms']:.2f}" for arm in ARMS]
        lines.append(label + ' & ' + ' & '.join(values) + r'\\')
    lines.extend([r'\bottomrule\end{tabular}',
                  r'\end{table}', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true',
                        help='verify existing table and summary without writing')
    args = parser.parse_args()
    result = retained()
    outputs = {'primary-mws-study.tex': table(result),
               'durable-mws-summary.json': json.dumps(result, indent=2) + '\n'}
    if args.check:
        for name, text in outputs.items():
            require((args.output / name).read_text(encoding='utf-8') == text,
                    f'stale durable table consumer: {name}')
    else:
        args.output.mkdir(parents=True, exist_ok=True)
        for name, text in outputs.items():
            (args.output / name).write_text(text, encoding='utf-8')
    print(json.dumps(dict(status='checked' if args.check else 'rendered',
                         cases=result['cases'], query_checks=result['query_checks'],
                         source='results/durable-mws-linux', arms=list(ARMS))))


if __name__ == '__main__':
    main()
